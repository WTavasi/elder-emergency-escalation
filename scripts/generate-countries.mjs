/**
 * Writes the country lists the phone fields use, in the app and in the console.
 *
 * Not part of any build. libphonenumber-js is not a dependency of the repository, so the
 * lists are generated once and committed, and regenerated only when the dialling plan
 * data is worth refreshing. To run it, from the repository root:
 *
 *   mkdir -p /tmp/countries && npm --prefix /tmp/countries install libphonenumber-js@1
 *   NODE_PATH=/tmp/countries/node_modules node scripts/generate-countries.mjs
 */
import { createRequire } from 'node:module';
import { writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
const require = createRequire((process.env.NODE_PATH ?? process.cwd() + '/node_modules') + '/');
const { Metadata, getCountries, getCountryCallingCode } = require('libphonenumber-js/core');
const json = require('libphonenumber-js/metadata.max.json');
const version = require('libphonenumber-js/package.json').version;
const names = new Intl.DisplayNames(['en'], { type: 'region' });
const md = new Metadata(json);
const rows = getCountries(json)
  .map((iso) => {
    md.selectNumberingPlan(iso);
    const lengths = md.numberingPlan.possibleLengths() || [];
    return {
      iso,
      name: names.of(iso),
      dial: getCountryCallingCode(iso, json),
      trunk: md.numberingPlan.nationalPrefix() || '',
      min: Math.min(...lengths),
      max: Math.max(...lengths),
    };
  })
  .sort((a, b) => a.name.localeCompare(b.name, 'en'));

const repo = fileURLToPath(new URL('..', import.meta.url));
const header = (c) =>
  [
    `${c} GENERATED by scripts/generate-countries.mjs from libphonenumber-js ${version}. Do not edit by hand.`,
    `${c}`,
    `${c} Every country with an international dialling code: its ISO code, English name,`,
    `${c} calling code, the trunk prefix people type before a local number (the 0 in`,
    `${c} 0712 345 678), and the shortest and longest national number it uses.`,
  ].join('\n');
const esc = (s) => s.replace(/\\/g, '\\\\').replace(/'/g, "\\'");

const dart = `${header('//')}

import 'country.dart';

const List<Country> countries = <Country>[
${rows.map((r) => `  Country('${r.iso}', '${esc(r.name)}', '${r.dial}', '${r.trunk}', ${r.min}, ${r.max}),`).join('\n')}
];
`;
mkdirSync(repo + '/frontend/mobile/lib/core/phone', { recursive: true });
writeFileSync(repo + '/frontend/mobile/lib/core/phone/countries.dart', dart);

const ts = `${header('//')}

import type { Country } from './country';

export const COUNTRIES: readonly Country[] = [
${rows.map((r) => `  { iso: '${r.iso}', name: '${esc(r.name)}', dial: '${r.dial}', trunk: '${r.trunk}', min: ${r.min}, max: ${r.max} },`).join('\n')}
];
`;
mkdirSync(repo + '/frontend/dashboard/src/shared/phone', { recursive: true });
writeFileSync(repo + '/frontend/dashboard/src/shared/phone/countries.ts', ts);
process.stdout.write(`${rows.length} countries, libphonenumber-js ${version}\n`);
